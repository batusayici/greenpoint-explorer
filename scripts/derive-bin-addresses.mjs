// One-time pull: resolve each loaded building's street address from its BBL via
// NYC PLUTO (Socrata), write a committed BIN->address map. Re-run manually when
// the loaded footprint set changes. NOT chained into npm run verify (network).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const BLOCKS = ["block-franklin-milton", "block-greenpoint-east"];
const ENDPOINT = "https://data.cityofnewyork.us/resource/64uk-42ks.json";

const binByBbl = new Map();
for (const b of BLOCKS) {
  const j = JSON.parse(readFileSync(join(ROOT, `src/data/geometry-source/${b}.nyc-open-geometry.v0.1.json`), "utf8"));
  for (const r of j.footprintRecords ?? []) {
    const sp = r.sourceProperties ?? {};
    if (sp.bin && sp.baseBbl) binByBbl.set(String(sp.baseBbl), String(sp.bin));
  }
}

const bbls = [...binByBbl.keys()];
const addresses = {};
for (let i = 0; i < bbls.length; i += 40) {
  const batch = bbls.slice(i, i + 40);
  const where = `bbl in(${batch.map((x) => `'${x}'`).join(",")})`;
  const url = `${ENDPOINT}?$select=bbl,address&$where=${encodeURIComponent(where)}`;
  const rows = await (await fetch(url)).json();
  for (const row of rows) {
    const bbl = String(row.bbl).split(".")[0];
    const bin = binByBbl.get(bbl);
    if (bin && row.address) addresses[bin] = row.address;
  }
}

const out = {
  _doc: "Generated by scripts/derive-bin-addresses.mjs — BIN -> street address from NYC PLUTO (Socrata). Re-run when the loaded footprint set changes. Not in the verify chain (network pull).",
  version: "0.1",
  addresses,
};
writeFileSync(join(ROOT, "src/data/real-data/bin-addresses.v0.1.json"), JSON.stringify(out, null, 2) + "\n");
console.log(`wrote ${Object.keys(addresses).length} addresses`);
